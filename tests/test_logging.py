"""Проверки безопасного удаления просроченных журналов."""

from datetime import date, timedelta
from pathlib import Path

from selfagent.logging import Logging


def test_удаляются_только_журналы_старше_срока_хранения(tmp_path: Path) -> None:
    """Свежие и нераспознанные каталоги остаются нетронутыми."""
    срок_хранения = 30
    просроченная_дата = date.today() - timedelta(days=срок_хранения + 1)
    граничная_дата = date.today() - timedelta(days=срок_хранения)
    свежая_дата = date.today() - timedelta(days=срок_хранения - 1)

    просроченный_каталог = tmp_path / просроченная_дата.isoformat()
    просроченный_каталог.mkdir()
    просроченный_журнал = просроченный_каталог / "Компонент.log"
    просроченный_журнал.write_text("старый журнал", encoding="utf-8")

    граничный_каталог = tmp_path / граничная_дата.isoformat()
    граничный_каталог.mkdir()
    граничный_журнал = граничный_каталог / "Компонент.log"
    граничный_журнал.write_text("журнал на границе срока", encoding="utf-8")

    свежий_каталог = tmp_path / свежая_дата.isoformat()
    свежий_каталог.mkdir()
    свежий_журнал = свежий_каталог / "Компонент.log"
    свежий_журнал.write_text("свежий журнал", encoding="utf-8")

    неизвестный_каталог = tmp_path / "не-дата"
    неизвестный_каталог.mkdir()
    неизвестный_журнал = неизвестный_каталог / "Компонент.log"
    неизвестный_журнал.write_text("журнал неизвестного каталога", encoding="utf-8")

    Logging._remove_expired_logs(tmp_path, срок_хранения)

    assert not просроченный_каталог.exists()
    assert граничный_журнал.read_text(encoding="utf-8") == "журнал на границе срока"
    assert свежий_журнал.read_text(encoding="utf-8") == "свежий журнал"
    assert неизвестный_журнал.read_text(encoding="utf-8") == "журнал неизвестного каталога"
